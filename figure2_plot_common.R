suppressPackageStartupMessages(library(ggplot2))

figure2_palette <- c(
  mESC_WT = "#F8766D", neuron_WT = "#C84C44",
  mESC_SF = "#00BA38", neuron_SF = "#00872A",
  mESC_KO = "#619CFF", neuron_KO = "#356BC2"
)
figure2_states <- c("mESC", "neuron")
figure2_genotypes <- c("WT", "SF", "KO")
figure2_facet_labels <- c(mESC = "mESC", neuron = "Ngn2-induced neuron")
figure2_theme <- theme_classic(base_size = 9) +
  theme(strip.background = element_rect(fill = "#E6E8EA", colour = NA),
        strip.text = element_text(face = "bold", colour = "#24282B"),
        axis.title = element_text(colour = "#24282B"),
        axis.text = element_text(colour = "#24282B"),
        legend.position = "none", panel.spacing = unit(0.8, "lines"),
        plot.margin = margin(4, 5, 4, 5))

save_figure2_panel <- function(plot, letter, width, height, out_dir) {
  dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)
  ggsave(file.path(out_dir, sprintf("Figure2%s.pdf", letter)), plot,
         width = width, height = height, units = "in",
         device = grDevices::pdf, bg = "white")
  ggsave(file.path(out_dir, sprintf("Figure2%s.png", letter)), plot,
         width = width, height = height, units = "in", dpi = 300,
         device = ragg::agg_png, background = "white")
}

make_figure2_overlap_plot <- function(data, y_title, letter) {
  # Older checked-in source tables called this value the mean because, with
  # two directions, the median and arithmetic mean are identical. Accept
  # both column names so the plotting scripts remain compatible with the
  # manuscript source tables and with tables regenerated by plot_figure2.R.
  if (!"median_reciprocal_overlap_percent" %in% names(data) &&
      "mean_reciprocal_overlap_percent" %in% names(data)) {
    data$median_reciprocal_overlap_percent <- data$mean_reciprocal_overlap_percent
  }
  required <- c("state", "genotype", "condition", "direction",
                "reciprocal_overlap_percent",
                "median_reciprocal_overlap_percent")
  missing <- setdiff(required, names(data))
  if (length(missing) > 0L) {
    stop("Missing required overlap columns: ", paste(missing, collapse = ", "),
         call. = FALSE)
  }
  data$state <- factor(data$state, levels = figure2_states,
                       labels = unname(figure2_facet_labels[figure2_states]))
  data$genotype <- factor(data$genotype, levels = figure2_genotypes)
  data$direction <- factor(data$direction,
                           levels = c("Rep1_to_Rep2", "Rep2_to_Rep1"),
                           labels = c("Rep1 to Rep2", "Rep2 to Rep1"))
  medians <- unique(data[c("state", "genotype", "median_reciprocal_overlap_percent")])
  dodge <- position_dodge(width = 0.28)
  ggplot(data, aes(x = genotype, y = reciprocal_overlap_percent,
                   colour = condition,
                   shape = direction, group = interaction(genotype, direction))) +
    geom_point(data = medians,
               aes(x = genotype, y = median_reciprocal_overlap_percent,
                   shape = "Median"),
               inherit.aes = FALSE, colour = "#343A40", size = 7, stroke = 0.8) +
    geom_point(position = dodge, size = 2.0, stroke = 0.55) +
    geom_text(data = medians,
              aes(x = genotype, y = median_reciprocal_overlap_percent,
                  label = sprintf("%.1f%%", median_reciprocal_overlap_percent)),
              inherit.aes = FALSE, colour = "#343A40", size = 2.2,
              position = position_nudge(x = 0.24), hjust = 0, vjust = -0.5) +
    facet_wrap(~state, nrow = 1) +
    scale_colour_manual(values = figure2_palette, guide = "none") +
    scale_shape_manual(values = c("Rep1 to Rep2" = 16,
                                  "Rep2 to Rep1" = 17,
                                  "Median" = 95), name = NULL,
                       breaks = c("Rep1 to Rep2", "Rep2 to Rep1", "Median")) +
    scale_x_discrete(expand = expansion(add = c(0.4, 0.8))) +
    scale_y_continuous(limits = c(50, 100), breaks = seq(50, 100, 10),
                       expand = expansion(mult = c(0.01, 0.06))) +
    labs(x = NULL, y = y_title, tag = letter) +
    figure2_theme + theme(legend.position = "bottom",
                          plot.tag = element_text(face = "bold", size = 13),
                          plot.tag.position = c(0, 1.02),
                          axis.text.x = element_text(face = "bold", size = 8),
                          strip.text = element_text(size = 8),
                          axis.title.y = element_text(size = 8),
                          legend.key.width = unit(0.45, "cm"))
}
